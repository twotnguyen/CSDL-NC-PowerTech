CREATE TABLE LOAIHANG (  -- Loại hàng
    MaLoai INT NOT NULL,
    TenLoai NVARCHAR(100) NOT NULL,
    MoTaLoai NVARCHAR(500) NULL,
    MaLoaiCha INT NULL,
    CONSTRAINT PK_LOAIHANG PRIMARY KEY (MaLoai),
    CONSTRAINT FK_LOAIHANG_MaLoaiCha FOREIGN KEY (MaLoaiCha) REFERENCES LOAIHANG(MaLoai),
    CONSTRAINT CK_LOAIHANG_1 CHECK (MaLoaiCha IS NULL OR MaLoaiCha <> MaLoai)
);

CREATE TABLE THUONGHIEU (  -- Thương hiệu
    MaTH INT NOT NULL,
    TenTH NVARCHAR(100) NOT NULL,
    MoTaTH NVARCHAR(500) NULL,
    CONSTRAINT PK_THUONGHIEU PRIMARY KEY (MaTH)
);

CREATE TABLE MATHANG (  -- Mặt hàng
    MaSP INT NOT NULL,
    SKU VARCHAR(50) NOT NULL,
    TenSP NVARCHAR(200) NOT NULL,
    MoTaSP NVARCHAR(2000) NULL,
    GiaNiemYet DECIMAL(15,0) NOT NULL,
    GiaKhuyenMai DECIMAL(15,0) NULL,
    ThoiHanBH INT NOT NULL,
    TinhTrangKD NVARCHAR(20) NOT NULL,
    CoSeri BIT NOT NULL,
    MaLoai INT NOT NULL,
    MaTH INT NOT NULL,
    CONSTRAINT PK_MATHANG PRIMARY KEY (MaSP),
    CONSTRAINT UQ_MATHANG_SKU UNIQUE (SKU),
    CONSTRAINT FK_MATHANG_MaLoai FOREIGN KEY (MaLoai) REFERENCES LOAIHANG(MaLoai),
    CONSTRAINT FK_MATHANG_MaTH FOREIGN KEY (MaTH) REFERENCES THUONGHIEU(MaTH),
    CONSTRAINT CK_MATHANG_1 CHECK (GiaNiemYet > 0),
    CONSTRAINT CK_MATHANG_2 CHECK (GiaKhuyenMai IS NULL OR GiaKhuyenMai <= GiaNiemYet),
    CONSTRAINT CK_MATHANG_3 CHECK (ThoiHanBH BETWEEN 0 AND 120),
    CONSTRAINT CK_MATHANG_4 CHECK (TinhTrangKD IN ('Đang kinh doanh', 'Ngừng kinh doanh'))
);

CREATE TABLE ANHMATHANG (  -- Ảnh mặt hàng
